def decode_8x8_tile(tile_bytes):
    pixels = []
    for y in range(8):
        b0 = tile_bytes[y]
        b1 = tile_bytes[y + 8]
        row = []
        for x in range(8):
            bit0 = (b0 >> (7 - x)) & 1
            bit1 = (b1 >> (7 - x)) & 1
            row.append((bit1 << 1) | bit0)
        pixels.append(row)
    return pixels

